-- ---------------------------------------------------------------------------
-- create_portfolio_invite: owner only, with Family, not while a rotation is
-- due, and for the key epoch the portfolio is on now. Replaces any invite
-- still pending for the portfolio. Once a partner holds the seat, invites
-- can only go to that partner.
-- ---------------------------------------------------------------------------
create function public.create_portfolio_invite(
  p_invite_id     uuid,
  p_portfolio_id  uuid,
  p_invitee_email text,
  p_wrapped_pk    bytea,
  p_key_epoch     integer
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  _uid       uuid := auth.uid();
  _email     text := lower(trim(p_invitee_email));
  _portfolio public.portfolios%rowtype;
  _invitee   uuid;
  _partner   uuid;
begin
  if _uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  select * into _portfolio from public.portfolios where id = p_portfolio_id for update;
  if not found or _portfolio.owner_id <> _uid then
    raise exception 'forbidden' using errcode = '42501';
  end if;
  if not public.has_family(_uid) then
    raise exception 'family_required' using errcode = '42501';
  end if;
  if _portfolio.rotation_due then
    raise exception 'rotation_due';
  end if;
  if _portfolio.key_epoch <> p_key_epoch then
    raise exception 'stale_epoch';
  end if;
  if _email !~ '^[^@[:space:]]+@[^@[:space:]]+$' then
    raise exception 'invalid_email';
  end if;
  if _email = (select lower(email) from auth.users where id = _uid) then
    raise exception 'self_invite';
  end if;

  select id into _invitee from auth.users where lower(email) = _email;
  if _invitee is not null and exists (
    select 1 from public.portfolio_members
    where portfolio_id = p_portfolio_id and user_id = _invitee
  ) then
    raise exception 'already_member';
  end if;

  select partner_id into _partner from public.family_partners where owner_id = _uid;
  if _partner is not null and _invitee is distinct from _partner then
    raise exception 'seat_taken';
  end if;

  delete from public.portfolio_invites
  where portfolio_id = p_portfolio_id and consumed_at is null;

  insert into public.portfolio_invites (id, portfolio_id, created_by, invitee_email, wrapped_pk_invite, key_epoch)
  values (p_invite_id, p_portfolio_id, _uid, _email, p_wrapped_pk, p_key_epoch);
end;
$$;

-- ---------------------------------------------------------------------------
-- Invite checks shared by get_ and accept_portfolio_invite. Returns 'ok' or
-- the reason the caller can't use the invite. Statuses that describe the
-- invite (used, expired, ...) come only after the email matches, so a
-- stranger holding the id learns nothing but "not for you".
-- ---------------------------------------------------------------------------
create function public.portfolio_invite_status(_invite public.portfolio_invites, _uid uuid)
returns text
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  _email     text;
  _confirmed timestamptz;
  _owner     uuid;
  _epoch     integer;
  _partner   uuid;
begin
  select owner_id, key_epoch into _owner, _epoch from public.portfolios where id = _invite.portfolio_id;
  if _owner is null then
    return 'not_found';
  end if;
  if _owner = _uid then
    return 'own_invite';
  end if;

  select lower(email), email_confirmed_at into _email, _confirmed from auth.users where id = _uid;
  if _email is distinct from _invite.invitee_email then
    return 'wrong_account';
  end if;
  if exists (
    select 1 from public.portfolio_members
    where portfolio_id = _invite.portfolio_id and user_id = _uid
  ) then
    return 'already_member';
  end if;
  if _confirmed is null then
    return 'unconfirmed';
  end if;
  if _invite.consumed_at is not null then
    return 'used';
  end if;
  if _invite.expires_at <= now() or _invite.key_epoch <> _epoch then
    return 'expired';
  end if;
  if not public.has_family(_owner) then
    return 'unavailable';
  end if;

  select partner_id into _partner from public.family_partners where owner_id = _owner;
  if _partner is not null and _partner <> _uid then
    return 'seat_taken';
  end if;
  if exists (select 1 from public.family_partners where partner_id = _uid and owner_id <> _owner) then
    return 'already_partnered';
  end if;
  return 'ok';
end;
$$;

-- What the invitee needs to accept: the wrapped PK and its context, plus the
-- inviter's email so they know who it's from. Everything but the status is
-- null unless the status is 'ok'.
create function public.get_portfolio_invite(p_invite_id uuid)
returns table (
  status       text,
  portfolio_id uuid,
  key_epoch    integer,
  wrapped_pk   bytea,
  invited_by   text,
  expires_at   timestamptz
)
language plpgsql
stable
security definer
set search_path = public
as $$
declare
  _uid    uuid := auth.uid();
  _invite public.portfolio_invites%rowtype;
  _status text;
begin
  if _uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  select * into _invite from public.portfolio_invites i where i.id = p_invite_id;
  if not found then
    return query select 'not_found'::text, null::uuid, null::integer, null::bytea, null::text, null::timestamptz;
    return;
  end if;

  _status := public.portfolio_invite_status(_invite, _uid);
  if _status <> 'ok' then
    return query select _status, null::uuid, null::integer, null::bytea, null::text, null::timestamptz;
    return;
  end if;

  return query
    select 'ok'::text, _invite.portfolio_id, _invite.key_epoch, _invite.wrapped_pk_invite,
           (select u.email::text from auth.users u where u.id = _invite.created_by),
           _invite.expires_at;
end;
$$;

-- ---------------------------------------------------------------------------
-- accept_portfolio_invite: single use. The portfolio row is locked first so
-- a rotation can't land between the checks and the insert. The consuming
-- UPDATE repeats the pending/unexpired/epoch conditions, clears the wrap,
-- and takes the seat; the member insert then passes enforce_portfolio_member.
-- ---------------------------------------------------------------------------
create function public.accept_portfolio_invite(p_invite_id uuid, p_wrapped_pk bytea)
returns text
language plpgsql
security definer
set search_path = public
as $$
declare
  _uid       uuid := auth.uid();
  _invite    public.portfolio_invites%rowtype;
  _portfolio public.portfolios%rowtype;
  _status    text;
begin
  if _uid is null then
    raise exception 'not_authenticated' using errcode = '42501';
  end if;

  select * into _invite from public.portfolio_invites where id = p_invite_id;
  if not found then
    return 'not_found';
  end if;
  select * into _portfolio from public.portfolios where id = _invite.portfolio_id for update;
  if not found then
    return 'not_found';
  end if;
  -- Re-read under the lock.
  select * into _invite from public.portfolio_invites where id = p_invite_id;

  _status := public.portfolio_invite_status(_invite, _uid);
  if _status <> 'ok' then
    return _status;
  end if;

  update public.portfolio_invites
  set consumed_at = now(), consumed_by = _uid, wrapped_pk_invite = null
  where id = p_invite_id
    and consumed_at is null
    and expires_at > now()
    and key_epoch = _portfolio.key_epoch;
  if not found then
    return 'used';
  end if;

  insert into public.family_partners (owner_id, partner_id)
  values (_portfolio.owner_id, _uid)
  on conflict (owner_id) do nothing;

  insert into public.portfolio_members (portfolio_id, user_id, wrapped_pk, key_epoch)
  values (_portfolio.id, _uid, p_wrapped_pk, _portfolio.key_epoch);

  return 'ok';
end;
$$;

-- ---------------------------------------------------------------------------
-- rotate_portfolio_key: owner only, once the owner is the only member left.
-- Writes the blob re-encrypted under the new PK, replaces the owner's wrap
-- (keeping the old one in portfolio_key_history) and clears rotation_due.
-- Pending invites wrap the old PK and are deleted.
-- ---------------------------------------------------------------------------
create function public.rotate_portfolio_key(
  p_id                uuid,
  p_expected_revision bigint,
  p_expected_epoch    integer,
  p_encrypted_data    bytea,
  p_nonce             bytea,
  p_enc_version       integer,
  p_owner_wrapped_pk  bytea
)
returns table (status text, current_revision bigint, current_epoch integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  _uid uuid := auth.uid();
  _p   public.portfolios%rowtype;
begin
  select * into _p from public.portfolios p where p.id = p_id for update;
  if not found or _p.owner_id <> _uid then
    return query select 'forbidden'::text, null::bigint, null::integer;
    return;
  end if;
  if _p.revision <> p_expected_revision or _p.key_epoch <> p_expected_epoch then
    return query select 'conflict'::text, _p.revision, _p.key_epoch;
    return;
  end if;
  if exists (
    select 1 from public.portfolio_members m
    where m.portfolio_id = p_id and m.user_id <> _uid
  ) then
    return query select 'members_remain'::text, _p.revision, _p.key_epoch;
    return;
  end if;

  insert into public.portfolio_key_history (portfolio_id, key_epoch, user_id, wrapped_pk)
  select m.portfolio_id, m.key_epoch, m.user_id, m.wrapped_pk
  from public.portfolio_members m
  where m.portfolio_id = p_id and m.user_id = _uid
  on conflict do nothing;

  update public.portfolios p
  set encrypted_data = p_encrypted_data,
      nonce          = p_nonce,
      enc_version    = p_enc_version,
      revision       = _p.revision + 1,
      key_epoch      = _p.key_epoch + 1,
      rotation_due   = false
  where p.id = p_id;

  update public.portfolio_members m
  set wrapped_pk = p_owner_wrapped_pk,
      key_epoch  = _p.key_epoch + 1
  where m.portfolio_id = p_id and m.user_id = _uid;

  delete from public.portfolio_invites i
  where i.portfolio_id = p_id and i.consumed_at is null;

  return query select 'ok'::text, _p.revision + 1, _p.key_epoch + 1;
end;
$$;

-- ---------------------------------------------------------------------------
-- list_portfolio_people: the members of every portfolio the caller is in,
-- with their emails, so each side can see who the portfolio is shared with.
-- ---------------------------------------------------------------------------
create function public.list_portfolio_people()
returns table (portfolio_id uuid, user_id uuid, email text, is_owner boolean, joined_at timestamptz)
language sql
stable
security definer
set search_path = public
as $$
  select m.portfolio_id, m.user_id, u.email::text, p.owner_id = m.user_id, m.created_at
  from public.portfolio_members m
  join public.portfolios p on p.id = m.portfolio_id
  join auth.users u on u.id = m.user_id
  where m.portfolio_id in (
    select mine.portfolio_id from public.portfolio_members mine where mine.user_id = auth.uid()
  )
  order by m.portfolio_id, m.created_at;
$$;

-- ---------------------------------------------------------------------------
-- release_owned_portfolios: run before an account's own rows are deleted
-- (account deletion, and the wipe after a password reset without a recovery
-- code). A portfolio with a partner passes to the partner, who already holds
-- its key; the others are deleted. Service role only.
-- ---------------------------------------------------------------------------
create function public.release_owned_portfolios(p_user_id uuid)
returns table (transferred integer, deleted integer)
language plpgsql
security definer
set search_path = public
as $$
declare
  _row         record;
  _transferred integer := 0;
  _deleted     integer := 0;
begin
  for _row in
    select p.id,
           (select m.user_id from public.portfolio_members m
            where m.portfolio_id = p.id and m.user_id <> p_user_id
            limit 1) as heir
    from public.portfolios p
    where p.owner_id = p_user_id
    for update of p
  loop
    if _row.heir is not null then
      update public.portfolios set owner_id = _row.heir where id = _row.id;
      _transferred := _transferred + 1;
    else
      delete from public.portfolios where id = _row.id;
      _deleted := _deleted + 1;
    end if;
  end loop;

  delete from public.family_partners where owner_id = p_user_id;
  return query select _transferred, _deleted;
end;
$$;

