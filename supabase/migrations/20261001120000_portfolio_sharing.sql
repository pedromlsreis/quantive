grant execute on function public.rotate_portfolio_key(uuid, bigint, integer, bytea, bytea, integer, bytea) to authenticated, service_role;
grant execute on function public.list_portfolio_people()                                   to authenticated, service_role;

-- ---------------------------------------------------------------------------
-- Daily purge: expired invites, and used ones after 30 days (kept that long
-- so a partner reopening the link is told it's used, not that it's unknown).
-- 03:20 UTC, offset from the other nightly jobs.
-- ---------------------------------------------------------------------------
create extension if not exists pg_cron with schema extensions;

select cron.schedule(
  'portfolio-invites-purge-daily',
  '20 3 * * *',
  $$
  delete from public.portfolio_invites
  where (consumed_at is null and expires_at < now())
     or consumed_at < now() - interval '30 days'
  $$
);
