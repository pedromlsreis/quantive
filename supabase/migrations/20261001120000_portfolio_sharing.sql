-- Anyone other than the owner must be the owner's partner.
create function public.enforce_portfolio_member()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  _owner uuid;
begin
  select owner_id into _owner from public.portfolios where id = new.portfolio_id;
  if _owner is not null and new.user_id <> _owner and not exists (
    select 1 from public.family_partners
    where owner_id = _owner and partner_id = new.user_id
  ) then
    raise exception 'not_partner' using errcode = '42501';
  end if;
  return new;
end;
$$;

create trigger enforce_portfolio_member
  before insert on public.portfolio_members
  for each row execute function public.enforce_portfolio_member();

-- A partner left or was removed: the owner must rotate the key, and any
-- invite still pending wraps the old key. The seat frees once the partner is
-- in none of the owner's portfolios.
--
-- When the whole portfolio is being deleted its row is already gone here,
-- so the update matches nothing; the seat check still runs.
create function public.after_portfolio_member_removed()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.portfolios
  set rotation_due = true
  where id = old.portfolio_id and owner_id <> old.user_id;

  if found then
    delete from public.portfolio_invites
    where portfolio_id = old.portfolio_id and consumed_at is null;
  end if;

  delete from public.family_partners fp
  where fp.partner_id = old.user_id
    and not exists (
      select 1
      from public.portfolio_members m
      join public.portfolios p on p.id = m.portfolio_id
      where p.owner_id = fp.owner_id and m.user_id = fp.partner_id
    );
  return old;
end;
$$;

create trigger after_portfolio_member_removed
  after delete on public.portfolio_members
  for each row execute function public.after_portfolio_member_removed();

-- Keep the version a save replaced, then trim to the newest 20, and drop
-- retired keys no kept version needs any more.
create function public.record_portfolio_revision()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.portfolio_revisions
    (portfolio_id, revision, key_epoch, encrypted_data, nonce, enc_version, saved_by, saved_at)
  values
    (old.id, old.revision, old.key_epoch, old.encrypted_data, old.nonce, old.enc_version, old.saved_by, old.saved_at)
  on conflict (portfolio_id, revision) do nothing;

  delete from public.portfolio_revisions
  where portfolio_id = old.id
    and revision < (
      select r.revision from public.portfolio_revisions r
      where r.portfolio_id = old.id
      order by r.revision desc
      offset 19 limit 1
    );

  delete from public.portfolio_key_history h
  where h.portfolio_id = old.id
    and h.key_epoch < (
      select min(r.key_epoch) from public.portfolio_revisions r
      where r.portfolio_id = old.id
    );
  return new;
end;
$$;

create trigger record_portfolio_revision
  after update of encrypted_data on public.portfolios
  for each row
  when (old.encrypted_data is distinct from new.encrypted_data)
  execute function public.record_portfolio_revision();

