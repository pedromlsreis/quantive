-- ===========================================================================
-- Sharing an extra portfolio with one partner (Family plan, phase 2).
-- Spec: docs/security/encryption.md §7.3, §8.7–§8.10.
--
-- The owner invites a partner by email. The portfolio key (PK) travels
-- wrapped under a secret S that exists only in the invite link's fragment,
-- so the server never holds anything that opens the portfolio. The partner
-- accepts by re-wrapping PK under their own DK.
--
-- One partner per owner (family_partners). Removing the partner, or the
-- partner leaving, sets rotation_due; the owner's browser then re-encrypts
-- under a new PK (rotate_portfolio_key).
--
-- As in phase 1, clients never INSERT or UPDATE these tables directly:
-- writes go through the SECURITY DEFINER functions below. The exceptions are
-- DELETEs a policy allows: an owner revoking an invite or removing the
-- partner, and a partner leaving.
-- ===========================================================================

-- ---------------------------------------------------------------------------
-- Who wrote the current blob, and when. A trigger sets both whenever the
-- ciphertext changes, so a flag change (rotation_due) doesn't count as a save.
-- ---------------------------------------------------------------------------
alter table public.portfolios
  add column saved_at timestamptz not null default now(),
  add column saved_by uuid default auth.uid() references auth.users(id) on delete set null;

create function public.stamp_portfolio_save()
returns trigger
language plpgsql
set search_path = public
as $$
begin
  if new.encrypted_data is distinct from old.encrypted_data then
    new.saved_at := now();
    new.saved_by := auth.uid();
  end if;
  return new;
end;
$$;

create trigger stamp_portfolio_save
  before update on public.portfolios
  for each row execute function public.stamp_portfolio_save();

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

-- The one partner seat per owner. partner_id is unique too: a person can be
-- the partner of only one owner.
create table public.family_partners (
  owner_id   uuid primary key references auth.users(id) on delete cascade,
  partner_id uuid not null unique references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  check (owner_id <> partner_id)
);

create table public.portfolio_invites (
  id                uuid primary key,  -- generated by the client: it is bound into the invite wrap's AAD
  portfolio_id      uuid not null references public.portfolios(id) on delete cascade,
  created_by        uuid not null references auth.users(id) on delete cascade,
  invitee_email     text not null check (invitee_email = lower(invitee_email) and length(invitee_email) between 3 and 320),
  -- PK wrapped under the link secret S: nonce(24) || ciphertext_with_tag(48).
  -- Present exactly while the invite is pending; accepting clears it.
  wrapped_pk_invite bytea check (wrapped_pk_invite is null or octet_length(wrapped_pk_invite) = 72),
  key_epoch         integer not null check (key_epoch >= 1),
  expires_at        timestamptz not null default now() + interval '7 days',
  consumed_at       timestamptz,
  consumed_by       uuid references auth.users(id) on delete set null,
  created_at        timestamptz not null default now(),
  check ((consumed_at is null) = (wrapped_pk_invite is not null))
);

create index portfolio_invites_created_by_idx on public.portfolio_invites (created_by);
-- At most one pending invite per portfolio; creating another replaces it.
create unique index portfolio_invites_one_pending_idx
  on public.portfolio_invites (portfolio_id) where consumed_at is null;

-- The ciphertexts a save replaced, newest 20 per portfolio. Lets a member put
-- back a version after a bad write, such as a partner overwriting the blob.
create table public.portfolio_revisions (
  portfolio_id   uuid not null references public.portfolios(id) on delete cascade,
  revision       bigint not null,
  key_epoch      integer not null,
  encrypted_data bytea not null,
  nonce          bytea not null,
  enc_version    integer not null,
  saved_by       uuid references auth.users(id) on delete set null,
  saved_at       timestamptz not null,
  primary key (portfolio_id, revision)
);

-- The owner's wrap of each retired PK. A rotation replaces the owner's
-- member row, and without the old wrap the revisions written before it could
-- no longer be opened, which is exactly when they're needed. The removed
-- partner already knew these keys, so keeping them costs nothing.
create table public.portfolio_key_history (
  portfolio_id uuid not null references public.portfolios(id) on delete cascade,
  key_epoch    integer not null,
  user_id      uuid not null references auth.users(id) on delete cascade,
  wrapped_pk   bytea not null check (octet_length(wrapped_pk) = 72),
  primary key (portfolio_id, key_epoch, user_id)
);

