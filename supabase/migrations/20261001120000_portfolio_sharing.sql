  on public.portfolio_key_history for select to authenticated
  using (user_id = auth.uid());

-- A partner may leave, and the owner may remove the partner. Nobody can
-- delete the owner's own row, so a partner can't lock the owner out.
create policy "partners can leave and owners can remove them"
  on public.portfolio_members for delete to authenticated
  using (
    (user_id = auth.uid() and not public.is_portfolio_owner(portfolio_id))
    or (user_id <> auth.uid() and public.is_portfolio_owner(portfolio_id))
  );

